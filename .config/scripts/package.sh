#!/usr/bin/env bash
# Build target/package/jvm-<version>.tar, a package.el archive. It holds the module for the host
# platform only. Install it with M-x package-install-file.
set -euo pipefail

cargo build --release

PKGID="$(cargo pkgid)"
VERSION="${PKGID##*[#@]}"
# Keep cargo's cdylib file name: jvm.el's `jvm--module-file' expects it.
SUFFIX="$(emacs -Q --batch --eval '(princ module-file-suffix)')"

OUT_DIR=target/package
PKG_DIR="$OUT_DIR/jvm-$VERSION"
rm -rf "$PKG_DIR"
rm -f "$OUT_DIR"/jvm-*.tar
mkdir -p "$PKG_DIR/module"
cp elisp/jvm.el elisp/jvm-clj.el "$PKG_DIR/"
# In a subdirectory, which package.el does not scan for autoloads: Emacs 28 reads a .dylib there as
# Lisp. `jvm-module-directory' points here.
cp target/release/*emacs_jni"$SUFFIX" "$PKG_DIR/module/"
# Sources, for browsing (e.g. `find-function' on a module function). They keep their checkout paths.
cp -r src java clojure "$PKG_DIR/"
cat > "$PKG_DIR/jvm-pkg.el" <<PKG
;; Generated by the mise package task  -*- no-byte-compile: t; lexical-binding: t -*-
(define-package "jvm" "$VERSION"
  "Embed a JVM in Emacs; call Java and Clojure from Lisp"
  '((emacs "28.1")))
PKG
tar -cf "$OUT_DIR/jvm-$VERSION.tar" -C "$OUT_DIR" "jvm-$VERSION"
echo "$OUT_DIR/jvm-$VERSION.tar"
